-- Пополнения звёздами живут в том же журнале, что и остальные движения: баланс
-- обязан объясняться одним ledger, без второй таблицы рядом.
--
-- ref_id у пополнения — это telegram_payment_charge_id. Telegram может
-- доставить одно и то же обновление повторно, и уникальный индекс делает
-- повторное зачисление невозможным на уровне БД, а не на уровне проверки.
CREATE UNIQUE INDEX IF NOT EXISTS ledger_topup_ref_idx
    ON ledger (ref_id) WHERE reason = 'topup';
